class Row(dict):
    def __getitem__(self,key):
        return list(self.values())[key] if isinstance(key,int) else super().__getitem__(key)

def row_factory(cursor):
    names=[c.name for c in cursor.description or ()]
    def convert(value):
        if isinstance(value,datetime):return value.astimezone(SHANGHAI).isoformat()
        if isinstance(value,date):return value.isoformat()
        return value
    return lambda values: Row(zip(names,map(convert,values)))

class JobTransaction:
    """Translate the frozen state-machine parameter syntax to native PG SQL."""
    def __init__(self,pg,key): self.pg=pg;self.key=key;self.locked=False
    def execute(self,query,params=()):
        if query=='BEGIN IMMEDIATE':
            self.locked=True
            return self.pg.execute('SELECT pg_advisory_xact_lock(%s)',(self.key,))
        if not self.locked and query.lstrip().split()[0].upper() in ('INSERT','UPDATE','DELETE'):
            self.pg.execute('SELECT pg_advisory_xact_lock(%s)',(self.key,));self.locked=True
        replacements={
            'INSERT OR REPLACE INTO scheduler_rearm VALUES(?,?,?)':'INSERT INTO scheduler_rearm VALUES(%s,%s,%s) ON CONFLICT(target) DO UPDATE SET revision=EXCLUDED.revision,reason=EXCLUDED.reason',
            'INSERT OR REPLACE INTO scheduler_dispatch VALUES(?,?)':'INSERT INTO scheduler_dispatch VALUES(%s,%s) ON CONFLICT(target) DO UPDATE SET job_id=EXCLUDED.job_id',
        }
        return self.pg.execute(replacements.get(query,query.replace('?', '%s')),params)

class DailyJobs(StateMachine):
    def __init__(self,root,executor=None,clock=None,source_probe=None):
        self.root=Path(root).resolve();self.clock=clock or (lambda:datetime.now(SHANGHAI))
        self.executor=executor;self.stop=threading.Event();self.thread=None;self.worker_error=None
        self.active_job_id=None;self.source_probe=source_probe;self.policy_binding=None
        self.dsn=configured_dsn();self.schema=workspace_schema(self.root,'jobs')
        self.lock_key=int.from_bytes(hashlib.sha256(self.schema.encode()).digest()[:8],'big',signed=True)
        calendar_mode=os.environ.get('V4_MARKET_CALENDAR_SOURCE','FILE')
        if calendar_mode not in {'FILE','PG'}:raise ValueError('MARKET_CALENDAR_SOURCE_UNSUPPORTED')
        head_path=self.root/'data/v4/V4_OPERATIONAL_RESEARCH_HEAD.json'
        if (calendar_mode=='PG' or (calendar_mode=='FILE' and head_path.is_file())):
            policy_path=self.root/'config/read_only_operational_daily_release_policy_v1_1.json'
            policy=json.loads(policy_path.read_bytes())
            if policy.get('contract_id')!='READ_ONLY_OPERATIONAL_DAILY_RELEASE_POLICY_V1_1' or any(policy.get(k) is not False for k in ('historical_PIT_permission','automated_trading_permission','algorithm_upgrade_permission')): raise ValueError('DAILY_POLICY_SCOPE_INVALID')
            task=(self.root/policy['task_contract']['path']).resolve()
            if not task.is_relative_to(self.root) or hashlib.sha256(task.read_bytes()).hexdigest()!=policy['task_contract']['sha256']: raise ValueError('DAILY_POLICY_TASK_BINDING_INVALID')
            self.policy_binding=dict(path=policy_path.relative_to(self.root).as_posix(),sha256=hashlib.sha256(policy_path.read_bytes()).hexdigest())
        with psycopg.connect(self.dsn,connect_timeout=5) as pg:
            create_schema(pg,self.schema)
        with connection(self.schema,dsn=self.dsn) as pg:
            pg.execute('SELECT pg_advisory_xact_lock(%s)',(self.lock_key,))
            pg.execute(DDL)

    def _gap_plan(self,through_date=None):
        if os.environ.get('V4_MARKET_CALENDAR_SOURCE','FILE')!='PG':
            return super()._gap_plan(through_date)
        from workbench_db.v4_market_calendar_reader_r1 import from_environment
        from .operational_daily_calendar_v2 import gap_plan
        calendar=from_environment().calendar()
        return gap_plan(self.root,self.clock(),through_date,
                        last_good_trade_date=calendar['accepted_trade_date'],
                        calendar_binding=calendar)

    @contextmanager
    def connect(self):
        with connection(self.schema,dsn=self.dsn,row_factory=row_factory) as pg:
            yield JobTransaction(pg,self.lock_key)

    @contextmanager
    def read_connect(self):
        """Use the explicit Reader DSN for scheduler-state queries."""
        with connection(self.schema,dsn=configured_reader_dsn(),read_only=True,row_factory=row_factory) as pg:
            yield pg

    @contextmanager
    def worker_lock(self):
        # Session lock spans executor calls without an idle open transaction.
        with psycopg.connect(self.dsn,autocommit=True,connect_timeout=5) as pg:
            key=self.lock_key ^ 1
            if not pg.execute('SELECT pg_try_advisory_lock(%s)',(key,)).fetchone()[0]:
                raise RuntimeError('V4_PG_WORKER_ALREADY_OWNED')
            try: yield
            finally: pg.execute('SELECT pg_advisory_unlock(%s)',(key,))

    def read_probe(self,target):
        with self.read_connect() as db:
            row=db.execute('SELECT payload FROM source_probe_state WHERE target=?',(target,)).fetchone()
        return row[0] if row else {}

    def write_probe(self,target,cached):
        from psycopg.types.json import Jsonb
        with self.connect() as db:
            db.execute('INSERT INTO source_probe_state VALUES(?,?,clock_timestamp()) ON CONFLICT(target) DO UPDATE SET payload=EXCLUDED.payload,updated_at=EXCLUDED.updated_at',(target,Jsonb(cached)))

    def checkpoint(self,day,stage,detail):
        if not self.active_job_id:return
        if stage=='PUBLISHING':
            # Cancellation admission and the final publication boundary use
            # the same job row. Neither side may overwrite the other's intent.
            with self.connect() as db:
                db.execute('BEGIN IMMEDIATE')
                row=db.execute('SELECT status FROM update_jobs WHERE job_id=? FOR UPDATE',(self.active_job_id,)).fetchone()
                if row is None:raise ValueError('JOB_NOT_FOUND')
                if row['status'] in {'CANCEL_REQUESTED','CANCELLED'}:return
                if row['status']!='RUNNING':raise ValueError('PUBLICATION_JOB_NOT_RUNNING')
                db.execute("UPDATE update_jobs SET status='PUBLISHING' WHERE job_id=?",(self.active_job_id,))
                db.execute('UPDATE update_job_days SET state=?,source_checks=? WHERE job_id=? AND trade_date=?',
                    (stage,json.dumps(detail),self.active_job_id,day))
                self.event(db,self.active_job_id,stage,'PUBLICATION_SAFE_BOUNDARY',dict(trade_date=day))
        else:super().checkpoint(day,stage,detail)
        self.record_progress(day,stage,detail)

    def record_progress(self,day,stage,detail):
        processed=detail.get('processed');total=detail.get('total')
        if processed is not None and (type(processed) is not int or processed<0):raise ValueError('INVALID_PROGRESS_COUNT')
        if total is not None and (type(total) is not int or total<0 or processed is not None and processed>total):raise ValueError('INVALID_PROGRESS_TOTAL')
        with self.connect() as db:
            db.execute("""INSERT INTO update_job_progress(job_id,trade_date,stage,stage_started_at,last_progress_at,heartbeat_at,processed,total,unit,recent_message,mode) VALUES(?,?,?,clock_timestamp(),clock_timestamp(),clock_timestamp(),?,?,?,?,?)
                ON CONFLICT(job_id) DO UPDATE SET trade_date=EXCLUDED.trade_date,stage=EXCLUDED.stage,
                stage_started_at=CASE WHEN update_job_progress.stage=EXCLUDED.stage AND update_job_progress.trade_date=EXCLUDED.trade_date THEN update_job_progress.stage_started_at ELSE EXCLUDED.stage_started_at END,
                last_progress_at=EXCLUDED.last_progress_at,processed=EXCLUDED.processed,total=EXCLUDED.total,
                heartbeat_at=EXCLUDED.heartbeat_at,unit=EXCLUDED.unit,recent_message=EXCLUDED.recent_message,mode=COALESCE(EXCLUDED.mode,update_job_progress.mode)""",
                (self.active_job_id,day,stage,processed,total,detail.get('unit'),str(detail.get('message',stage))[:500],detail.get('mode')))
            if stage in {'FAILED_TERMINAL','CANCELLED','CANCELLED_SYSTEM','INTERRUPTED','QA_BLOCKED'}:
                db.execute("UPDATE update_jobs SET finished_at=COALESCE(finished_at,?) WHERE job_id=? AND status IN ('FAILED_TERMINAL','CANCELLED','CANCELLED_SYSTEM','INTERRUPTED','QA_BLOCKED')",(self.clock().isoformat(),self.active_job_id))

    def progress(self):
        # One small row; no gap planner or Owner decoding on this polling path.
        with self.read_connect() as db:
            row=db.execute("""SELECT j.job_id,COALESCE(p.mode,j.mode) AS mode,j.mode AS job_mode,j.through_date AS target_trade_date,j.status AS stage_state,
                j.created_at AS started_at,j.finished_at,j.error AS error_code,p.stage,p.stage_started_at,p.last_progress_at,
                p.processed,p.total,p.unit,p.recent_message,p.heartbeat_at,
                EXTRACT(EPOCH FROM COALESCE(j.finished_at,clock_timestamp())-j.created_at) AS elapsed_seconds,
                EXTRACT(EPOCH FROM COALESCE(j.finished_at,clock_timestamp())-p.stage_started_at) AS stage_elapsed_seconds,
                EXTRACT(EPOCH FROM clock_timestamp()-p.last_progress_at) AS seconds_since_progress
                FROM update_jobs j LEFT JOIN update_job_progress p USING(job_id)
                ORDER BY CASE WHEN j.status IN ('RUNNING','PUBLISHING','CANCEL_REQUESTED') THEN 0 ELSE 1 END,j.created_at DESC LIMIT 1""").fetchone()
            accepted=db.execute("""SELECT MAX(d.trade_date) AS last_published_trade_date
                FROM update_job_days d JOIN update_jobs j USING(job_id)
                WHERE j.mode='CATCH_UP' AND d.state='PUBLISHED'""").fetchone()
        result=dict(row) if row else dict(stage_state='IDLE')
        for key in ('elapsed_seconds','stage_elapsed_seconds','seconds_since_progress'):
            if result.get(key) is not None:result[key]=float(result[key])
        result.update(contract_id='V4_DAILY_PROGRESS_R1',eta_seconds=None,error_detail=None,
                      head_unchanged=result.get('stage_state') not in ('PUBLISHED_FULL',),worker_error=self.worker_error)
        # Daily acceptance state is owned by PG job-day receipts. Do not rebuild
        # a second Head from the legacy operational JSON in this polling path.
        result['last_published_trade_date']=(accepted['last_published_trade_date'] if accepted else None)
        return result

    def job(self,job):
        with self.read_connect() as db:
            row=db.execute('SELECT * FROM update_jobs WHERE job_id=?',(job,)).fetchone()
            if not row:raise ValueError('JOB_NOT_FOUND')
            days=[dict(x) for x in db.execute('SELECT * FROM update_job_days WHERE job_id=? ORDER BY trade_date',(job,))]
        for day in days:day['source_checks']=json.loads(day['source_checks'])
        return dict(row)|dict(days=days)

    def events(self,job,after=0):
        self.job(job)
        with self.read_connect() as db:
            return [dict(x) for x in db.execute('SELECT * FROM update_events WHERE job_id=? AND event_id>? ORDER BY event_id LIMIT 100',(job,after))]

    def settings(self,enabled=None):
        if enabled is not None:
            if not isinstance(enabled,bool):raise ValueError('ENABLED_BOOLEAN_REQUIRED')
            with self.connect() as db:
                db.execute('UPDATE scheduler_policy SET enabled=?,revision=revision+1,updated_at=? WHERE id=1',
                           (int(enabled),self.clock().isoformat()))
                self.event(db,None,'SETTINGS','AUTO_RESUMED' if enabled else 'AUTO_PAUSED_BY_USER',{})
        with self.read_connect() as db:
            row=dict(db.execute('SELECT * FROM scheduler_policy WHERE id=1').fetchone())
        return dict(contract_id='READ_ONLY_OPERATIONAL_DAILY_RELEASE_POLICY_V1_1',
            auto_enabled=bool(row['enabled']),revision=row['revision'],updated_at=row['updated_at'],
            first_check='18:35',timezone='Asia/Shanghai',retry_times=RETRY_TIMES,
            service_alive=self.thread is not None and self.thread.is_alive(),
            operational_mode='AUTO_ON' if row['enabled'] else 'AUTO_PAUSED_BY_USER',
            permission_scope='READ_ONLY_OPERATIONAL_RESEARCH',
            publication_ready=(json.loads((self.root/self.policy_binding['path']).read_bytes()).get('publication_ready',False) if self.policy_binding else False),
            policy_binding=self.policy_binding)

    def status(self):
        plan=self._gap_plan()
        with self.read_connect() as db:
            row=db.execute('SELECT job_id FROM update_jobs ORDER BY created_at DESC LIMIT 1').fetchone()
            active=db.execute("SELECT job_id FROM update_jobs WHERE mode='CATCH_UP' AND status NOT IN ('PUBLISHED_FULL','NOOP_ALREADY_CURRENT','FAILED_TERMINAL','CANCELLED','CANCELLED_SYSTEM','INTERRUPTED','QA_BLOCKED') ORDER BY created_at LIMIT 1").fetchone()
            last_catch_up=db.execute("SELECT job_id FROM update_jobs WHERE mode='CATCH_UP' ORDER BY created_at DESC LIMIT 1").fetchone()
        active_record=self.job(active['job_id']) if active else None
        retry_times=[d['next_retry_at'] for d in (active_record or {}).get('days',[]) if d['next_retry_at']]
        if retry_times:
            plan['next_trigger_at']=min(retry_times+([plan['next_trigger_at']] if plan.get('next_trigger_at') else []))
        return dict(plan,settings=self.settings(),last_job=self.job(row['job_id']) if row else None,
                    active_job=active_record,
                    last_catch_up_job=self.job(last_catch_up['job_id']) if last_catch_up else None,
                    worker_error=self.worker_error,last_good_preserved=True)


