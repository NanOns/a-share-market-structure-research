-- Fixed R1 scheduler relations; migration receipts precede append-only guards.
CREATE TABLE IF NOT EXISTS v4.jobs_scheduler_policy_r1(
 id integer PRIMARY KEY CHECK(id=1),enabled integer NOT NULL CHECK(enabled IN (0,1)),
 revision bigint NOT NULL CHECK(revision>0),updated_at timestamptz NOT NULL);
CREATE TABLE IF NOT EXISTS v4.jobs_update_jobs_r1(
 job_id text PRIMARY KEY,trigger text NOT NULL,mode text NOT NULL CHECK(mode IN ('CATCH_UP','PROBE')),
 through_date date NOT NULL,status text NOT NULL,created_at timestamptz NOT NULL,finished_at timestamptz,
 idempotency_key text UNIQUE,error text);
CREATE TABLE IF NOT EXISTS v4.jobs_scheduler_dispatch_r1(
 target date PRIMARY KEY,job_id text NOT NULL REFERENCES v4.jobs_update_jobs_r1(job_id));
CREATE TABLE IF NOT EXISTS v4.jobs_scheduler_attempts_r1(
 target date,attempt_ordinal integer CHECK(attempt_ordinal>0),job_id text UNIQUE REFERENCES v4.jobs_update_jobs_r1(job_id),
 old_job_id text REFERENCES v4.jobs_update_jobs_r1(job_id),source_revision text,reason text NOT NULL,
 created_at timestamptz NOT NULL,PRIMARY KEY(target,attempt_ordinal));
CREATE TABLE IF NOT EXISTS v4.jobs_scheduler_rearm_r1(
 target date PRIMARY KEY,revision text NOT NULL,reason text NOT NULL);
CREATE TABLE IF NOT EXISTS v4.jobs_update_job_days_r1(
 job_id text REFERENCES v4.jobs_update_jobs_r1(job_id),trade_date date,state text NOT NULL,
 attempt_count integer NOT NULL DEFAULT 0 CHECK(attempt_count>=0),next_retry_at timestamptz,
 source_checks text NOT NULL DEFAULT '{}',PRIMARY KEY(job_id,trade_date));
CREATE INDEX IF NOT EXISTS jobs_update_job_days_published_trade_date_r1
 ON v4.jobs_update_job_days_r1(trade_date) WHERE state='PUBLISHED';
CREATE TABLE IF NOT EXISTS v4.jobs_update_events_r1(
 event_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,job_id text REFERENCES v4.jobs_update_jobs_r1(job_id),
 timestamp timestamptz NOT NULL,stage text NOT NULL,event_code text NOT NULL,safe_detail text NOT NULL);
CREATE INDEX IF NOT EXISTS jobs_status_time_r1 ON v4.jobs_update_jobs_r1(status,created_at,job_id);
CREATE INDEX IF NOT EXISTS jobs_events_r1 ON v4.jobs_update_events_r1(job_id,event_id);
CREATE TABLE IF NOT EXISTS v4.jobs_update_job_progress_r1(
 job_id text PRIMARY KEY REFERENCES v4.jobs_update_jobs_r1(job_id),trade_date date NOT NULL,stage text NOT NULL,
 stage_started_at timestamptz NOT NULL,last_progress_at timestamptz NOT NULL,processed bigint,total bigint,
 unit text,recent_message text,heartbeat_at timestamptz,mode text);
CREATE TABLE IF NOT EXISTS v4.jobs_source_probe_state_r1(
 target text PRIMARY KEY,payload jsonb NOT NULL,updated_at timestamptz NOT NULL DEFAULT clock_timestamp());

CREATE TABLE IF NOT EXISTS v4.jobs_migration_map_r1(
 source_schema text PRIMARY KEY,
 target_namespace text NOT NULL,
 table_counts jsonb NOT NULL,
 verification jsonb NOT NULL,
 migrated_at timestamptz NOT NULL DEFAULT clock_timestamp());
